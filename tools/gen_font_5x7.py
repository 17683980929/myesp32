G['"'] = [".#.#.", ".#.#.", ".....", ".....", ".....", ".....", "....."]

# 度号：3x3 小圆圈，占左上，用单独字形
G["~"] = [".##..", "#..#.", ".##..", ".....", ".....", ".....", "....."]

W, H = 5, 7
ADV = 6          # 步进宽度（5 像素 + 1 像素间隔）

ORDER = (
    " ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "0123456789"
    ":.,-+/%()!?=_*#<>'\"~"
)


def glyph_to_bytes(rows):
    """7 行 → 7 字节，每行低 5 位有效，MSB 是左边像素"""
    out = []
    for row in rows:
        v = 0
        for i, ch in enumerate(row):
            if ch == "#":
                v |= 1 << (7 - i)
        out.append(v)
    return out


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "."
    os.makedirs(out_dir, exist_ok=True)

    # 字符 → 索引
    index = {}
    glyphs = []
    for ch in ORDER:
        if ch in index:
            continue
        if ch not in G:
            print(f"⚠ 缺少字形: {ch!r}")
            continue
        index[ch] = len(glyphs)
        glyphs.append((ch, glyph_to_bytes(G[ch])))

    # 补一个"未知字符"字形（放在最后）
    unknown = len(glyphs)
    glyphs.append(("?", glyph_to_bytes(G["?"])))

    # ── 头文件 ──
    h_path = os.path.join(out_dir, "font5x7.h")
    with open(h_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("""/* 自动生成，请勿手改。生成器: tools/gen_font_5x7.py */
#pragma once
#include <stdint.h>

#define FONT5X7_W    5
#define FONT5X7_H    7
#define FONT5X7_ADV  6

/* 取一个字符的字形数据（7 字节，每行低 5 位有效，MSB 为左）。
   未收录的字符返回 '?' 的字形。返回 NULL 表示不打印。 */
const uint8_t *font5x7_glyph(char c);

/* 该字符的步进宽度（像素） */
uint8_t font5x7_advance(char c);
""")
    print(f"  → {h_path}")

    # ── 源文件 ──
    c_path = os.path.join(out_dir, "font5x7.c")
    with open(c_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* 自动生成，请勿手改。生成器: tools/gen_font_5x7.py */\n")
        f.write('#include "font5x7.h"\n\n')

        f.write(f"/* 共 {len(glyphs)} 个字形，每个 {H} 字节 */\n")
        f.write("static const uint8_t glyphs[][7] = {\n")
        for ch, data in glyphs:
            label = ch if ch not in ('"', "\\", "'") else "?"
            f.write(
                "    {" + ",".join(f"0x{b:02X}" for b in data) + "},  /* '" + label + "' */\n"
            )
        f.write("};\n\n")

        # 索引表：0x20..0x7E
        f.write("/* ASCII 0x20..0x7E → 字形索引，0xFF 表示未收录 */\n")
        f.write("static const uint8_t idx[95] = {\n    ")
        row = []
        for code in range(0x20, 0x7F):
            ch = chr(code)
            row.append(f"0x{index[ch]:02X}" if ch in index else "0xFF")
            if len(row) == 16:
                f.write(",".join(row) + ",\n    ")
                row = []
        if row:
            f.write(",".join(row) + ",\n")
        f.write("};\n\n")

        f.write(f"""const uint8_t *font5x7_glyph(char c)
{{
    unsigned char u = (unsigned char)c;
    if (u < 0x20 || u > 0x7E) return glyphs[{unknown}];
    uint8_t i = idx[u - 0x20];
    return glyphs[i == 0xFF ? {unknown} : i];
}}

uint8_t font5x7_advance(char c)
{{
    return FONT5X7_ADV;
}}
""")
    print(f"  → {c_path}")

    total = len(glyphs) * H
    print(f"  字形 {len(glyphs)} 个，数据 {total} 字节")


if __name__ == "__main__":
    main()
