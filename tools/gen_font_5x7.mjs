const W = 5, H = 7;

const ORDER =
    " ABCDEFGHIJKLMNOPQRSTUVWXYZ" +
    "abcdefghijklmnopqrstuvwxyz" +
    "0123456789" +
    ":.,-+/%()!?=_*#<>'\"~";

function glyphToBytes(rows) {
    // 7 行 → 7 字节，每行低 5 位有效，MSB 是左边像素
    return rows.map((row) => {
        let v = 0;
        for (let i = 0; i < row.length; i++) {
            if (row[i] === "#") v |= 1 << (7 - i);
        }
        return v;
    });
}

function main() {
    const outDir = process.argv[2] || ".";
    fs.mkdirSync(outDir, { recursive: true });

    // 字符 → 索引
    const index = new Map();
    const glyphs = [];
    for (const ch of ORDER) {
        if (index.has(ch)) continue;
        if (!(ch in G)) {
            console.log(`⚠ 缺少字形: ${JSON.stringify(ch)}`);
            continue;
        }
        index.set(ch, glyphs.length);
        glyphs.push([ch, glyphToBytes(G[ch])]);
    }

    // 补一个"未知字符"字形（放在最后）
    const unknown = glyphs.length;
    glyphs.push(["?", glyphToBytes(G["?"])]);

    // ── 头文件 ──
    const hPath = path.join(outDir, "font5x7.h");
    fs.writeFileSync(hPath, `/* 自动生成，请勿手改。生成器: tools/gen_font_5x7.mjs */
#pragma once
#include <stdint.h>

#define FONT5X7_W    5
#define FONT5X7_H    7
#define FONT5X7_ADV  6

/* 取一个字符的字形数据（7 字节，每行低 5 位有效，MSB 为左）。
   未收录的字符返回 '?' 的字形。返回 NULL 表示不打印。 */
const uint8_t *font5x7_glyph(char c);

/* 该字符的步进宽度（像素） */
uint8_t font5x7_advance(char c);
`);
    console.log(`  → ${hPath}`);

    // ── 源文件 ──
    const cPath = path.join(outDir, "font5x7.c");
    let c = "";
    c += "/* 自动生成，请勿手改。生成器: tools/gen_font_5x7.mjs */\n";
    c += '#include "font5x7.h"\n\n';
    c += `/* 共 ${glyphs.length} 个字形，每个 ${H} 字节 */\n`;
    c += "static const uint8_t glyphs[][7] = {\n";
    for (const [ch, data] of glyphs) {
        const label = ['"', "\\", "'"].includes(ch) ? "?" : ch;
        c += "    {" + data.map((b) => `0x${b.toString(16).toUpperCase().padStart(2, "0")}`).join(",") +
             `},  /* '${label}' */\n`;
    }
    c += "};\n\n";

    // 索引表：0x20..0x7E
    c += "/* ASCII 0x20..0x7E → 字形索引，0xFF 表示未收录 */\n";
    c += "static const uint8_t idx[95] = {\n    ";
    const row = [];
    for (let code = 0x20; code <= 0x7E; code++) {
        const ch = String.fromCharCode(code);
        row.push(index.has(ch) ? `0x${index.get(ch).toString(16).toUpperCase().padStart(2, "0")}` : "0xFF");
        if (row.length === 16) {
            c += row.join(",") + ",\n    ";
            row.length = 0;
        }
    }
    if (row.length) c += row.join(",") + ",\n";
    c += "};\n\n";

    c += `const uint8_t *font5x7_glyph(char c)
{
    unsigned char u = (unsigned char)c;
    if (u < 0x20 || u > 0x7E) return glyphs[${unknown}];
    uint8_t i = idx[u - 0x20];
    return glyphs[i == 0xFF ? ${unknown} : i];
}

uint8_t font5x7_advance(char c)
{
    return FONT5X7_ADV;
}
`;
    fs.writeFileSync(cPath, c);
    console.log(`  → ${cPath}`);
    console.log(`  字形 ${glyphs.length} 个，数据 ${glyphs.length * H} 字节`);
}

main();
